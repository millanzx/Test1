# Функция для обработки количества мест
def extract_places(budget_seats_str):
    # Ищем число в строке вида "15 мест (2025)" или "Есть бюджетные места (2025)"
    match = re.search(r'(\d+)', str(budget_seats_str))
    if match:
        return int(match.group(1))
    else:
        return 0

# Функция для определения тегов
def get_tags(budget_seats_str):
    if "бюджет" in str(budget_seats_str).lower() or "мест" in str(budget_seats_str):
        return ["Бюджет"]
    else:
        return ["Есть места"]

